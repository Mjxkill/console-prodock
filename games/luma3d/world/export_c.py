#!/usr/bin/env python3
"""Export the exact JSON geometry to native G3D1 records and a C asset catalogue."""
from collections import defaultdict
import argparse,hashlib,json,math,struct
from pathlib import Path

HERE=Path(__file__).resolve().parent
def f(v):
 assert math.isfinite(v)
 return f'{v:.7f}f'
def vec(v):return '{'+','.join(f(x) for x in v)+'}'
def quote(s):return json.dumps(s,ensure_ascii=False)
def word(v):return v&0xffffffff
def fixed(v):
 n=round(v*65536);assert -2**31<=n<2**31;return word(n)
def uv(v):
 n=round(v);assert -32768<=n<=32767;return n&65535
def array(lines,name,kind,values,per=8):
 lines.append(f'_Alignas(32) static const {kind} {name}[]={{')
 for start in range(0,len(values),per):lines.append(','.join(values[start:start+per])+',')
 lines.append('};')

def main():
 parser=argparse.ArgumentParser();parser.add_argument('--texture-dir',type=Path);parser.add_argument('--output',type=Path);parser.add_argument('--project-object-uv',action='store_true');args=parser.parse_args()
 texture_dir=(args.texture_dir or HERE.parent/'art').resolve();output=(args.output or HERE/'data.c').resolve()
 selection=HERE.parent/'art/material_selection.json'
 project_uv=args.project_object_uv or (not args.texture_dir and selection.exists() and json.loads(selection.read_text()).get('project_object_uv',False))
 output.parent.mkdir(parents=True,exist_ok=True)
 scene=json.loads((HERE/'scene.json').read_text());sources=json.loads((HERE/'meshes.json').read_text())['meshes']
 terrain=json.loads((HERE/'heightfield.json').read_text())
 texmanifest=json.loads((HERE.parent/'art/textures.json').read_text())
 lines=['/* Generated by world/export_c.py from the authored JSON. */','#include "generated.h"']
 textures=texmanifest['textures'];texture_ids={t['id']:i for i,t in enumerate(textures)}
 for i,t in enumerate(textures):
  raw=(texture_dir/t['file']).read_bytes();assert len(raw)==32768
  values=struct.unpack('<16384H',raw);array(lines,'l3_tex_'+str(i),'uint16_t',[hex(x) for x in values],16)
 lines.append('const L3AssetTexture l3_asset_textures[]={')
 lines.extend('{'+quote(t['id'])+f',l3_tex_{i},128,128'+'},' for i,t in enumerate(textures));lines.append('};')
 lines.append(f'const unsigned l3_asset_texture_count={len(textures)};')
 lines.append('const L3AssetMaterial l3_asset_materials[]={')
 for m in scene['materials']:
  tid=texture_ids[Path(m['texture']).stem]
  lines.append('{'+quote(m['name'])+','+','.join(map(str,[tid,*m['color'],0]))+'},')
 lines+=['};',f'const unsigned l3_asset_material_count={len(scene["materials"])};']
 groups=[];catalogue=[];geometry_bytes=0
 for name,mesh in sources.items():
  first=len(groups);by_material=defaultdict(list)
  for face in mesh['faces']:by_material[face['material']].append(face)
  for material,faces in sorted(by_material.items()):
   used=sorted({i for face in faces for i in face['indices']});remap={idx:n for n,idx in enumerate(used)}
   assert len(used)<=256 and len(faces)<65536,(name,material,len(used),len(faces))
   vertices=[];packed=[]
   for idx in used:vertices.extend([*[fixed(v) for v in mesh['vertices'][idx]],0,0,0,0,0])
   for face in faces:
    ids=[remap[v] for v in face['indices']];assert len(set(ids))==3
    n=[round(v*32767) for v in face['normal']];assert all(-32767<=v<=32767 for v in n)
    color=[round(a*b*256/(255*255)) for a,b in zip(scene['materials'][material]['color'],face['color'])]
    assert all(0<=v<=256 for v in color)
    mapping=face['uv']
    if project_uv and not name.startswith('terrain_') and name not in ('lake','river','waterfall'):
     dominant=max(range(3),key=lambda axis:abs(face['normal'][axis]));mapping=[]
     for index in face['indices']:
      x,y,z=mesh['vertices'][index]
      mapping.append([z*32,-y*32] if dominant==0 else [x*32,z*32] if dominant==1 else [x*32,-y*32])
    packed.extend([ids[0]|ids[1]<<8|ids[2]<<16,*[(uv(u)<<16)|uv(v) for u,v in mapping],
      (n[0]&65535)<<16|(n[1]&65535),n[2]&65535,color[0]|color[1]<<9|color[2]<<18,0])
   gi=len(groups);array(lines,f'l3_vertices_{gi}','uint32_t',[hex(word(x))+'u' for x in vertices]);array(lines,f'l3_faces_{gi}','uint32_t',[hex(word(x))+'u' for x in packed])
   groups.append(dict(nv=len(used),nf=len(faces),material=material));geometry_bytes+=4*(len(vertices)+len(packed))
  v=mesh['vertices'];low=mesh['bounds']['min'];high=mesh['bounds']['max'];center=[(a+b)/2 for a,b in zip(low,high)];radius=max(math.dist(p,center) for p in v)
  catalogue.append(dict(name=name,first=first,count=len(groups)-first,center=center,radius=radius))
 lines.append('const L3AssetGroup l3_asset_groups[]={')
 lines.extend('{'+f'l3_vertices_{i},l3_faces_{i},{g["nv"]},{g["nf"]},{g["material"]},0'+'},' for i,g in enumerate(groups));lines+=['};',f'const unsigned l3_asset_group_count={len(groups)};']
 lines.append('const L3AssetMesh l3_asset_meshes[]={')
 for m in catalogue:lines.append('{'+quote(m['name'])+f',l3_asset_groups+{m["first"]},{m["count"]},0,'+vec(m['center'])+','+f(m['radius'])+'},')
 lines+=['};',f'const unsigned l3_asset_mesh_count={len(catalogue)};']
 mesh_ids={m['name']:i for i,m in enumerate(catalogue)}
 kinds=dict(prop=0,terrain=1,water=2,waterfall=3,bridge=4,actor=5)
 lines.append('const L3AssetInstance l3_asset_instances[]={')
 for obj in scene['instances']:
  lods=obj.get('lods',[]);assert len(lods)<=2
  lod='{'+','.join('{'+f(x['distance'])+','+str(mesh_ids[x['mesh']])+',0}' for x in lods)+'}' if lods else '{{0,0,0},{0,0,0}}'
  lines.append('{'+quote(obj['id'])+f',{mesh_ids[obj["mesh"]]},{len(lods)},{kinds[obj["kind"]]},'+vec(obj['position'])+','+vec(obj['scale'])+','+f(obj['yaw'])+','+lod+'},')
 lines+=['};',f'const unsigned l3_asset_instance_count={len(scene["instances"])};']
 lines.append('const L3AssetCollider l3_asset_colliders[]={')
 for c in scene['colliders']:
  values=[c.get(k,0) for k in ['x','z','radius','min_y','max_y','length','width','y','arch_height','yaw']]
  lines.append('{'+quote(c['id'])+','+str(dict(circle=1,box=2,walkable_bridge=3)[c['kind']])+',0,'+','.join(f(v) for v in values)+'},')
 lines+=['};',f'const unsigned l3_asset_collider_count={len(scene["colliders"])};']
 points=[];water_records=[]
 for w in scene['water_zones']:
  pts=w.get('points',[]);water_records.append((w,len(points),len(pts)));points+=pts
 lines.append('const L3AssetPoint2 l3_asset_water_points[]={'+','.join(vec(p) for p in points)+'};')
 lines.append(f'const unsigned l3_asset_water_point_count={len(points)};')
 lines.append('const L3AssetWater l3_asset_waters[]={')
 for w,start,count in water_records:
  lines.append('{'+quote(w['id'])+f',{1 if w["kind"]=="ellipse" else 2},{start},{count},0,'+','.join(f(w.get(k,0)) for k in ['x','z','rx','rz','width','level'])+'},')
 lines+=['};',f'const unsigned l3_asset_water_count={len(water_records)};']
 lines.append('const float l3_asset_heights[81][81]={'+',\n'.join(vec(row) for row in terrain['heights'])+'};')
 lines.append('const L3Vec3 l3_asset_spawn='+vec(scene['spawn']['position'])+';')
 lines.append('const float l3_asset_spawn_yaw='+f(scene['spawn']['heading'])+';')
 route=[[p['x'],p['y'],p['z']] for p in scene['gameplay']['route']]
 lines.append('const L3Vec3 l3_asset_route[]={'+','.join(vec(p) for p in route)+'};')
 lines.append(f'const unsigned l3_asset_route_count={len(route)};')
 letters=scene['gameplay']['collectibles'];lines.append('const L3Vec3 l3_asset_collectibles[]={'+','.join(vec(p['position']) for p in letters)+'};')
 lines.append('const char *const l3_asset_collectible_names[]={'+','.join(quote(p['name']) for p in letters)+'};')
 lines.append(f'const unsigned l3_asset_collectible_count={len(letters)};')
 lines.append('const L3Vec3 l3_asset_goal='+vec(scene['gameplay']['goal']['position'])+';')
 lines.append('const float l3_asset_goal_radius='+f(scene['gameplay']['goal']['radius'])+';')
 lines.append('const L3Vec3 l3_asset_light_direction='+vec(scene['light']['direction'])+';')
 for key in ['ambient','fog_start','fog_end']:lines.append('const float l3_asset_'+key+'='+f(scene['light'][key])+';')
 for name,color in [('fog_color',scene['light']['fog_color']),('sky_horizon',scene['sky']['horizon']),('sky_zenith',scene['sky']['zenith'])]:lines.append('const uint8_t l3_asset_'+name+'[3]={'+','.join(map(str,color))+'};')
 lines.append(f'const unsigned l3_asset_hero_mesh={mesh_ids["hero"]};')
 animation=scene['animated_models'];parts=animation['hero']
 lines.append('const L3AssetPart l3_asset_hero_parts[]={'+','.join('{'+str(mesh_ids[p['mesh']])+','+str(p['kind'])+','+vec(p['pivot'])+'}' for p in parts)+'};')
 lines.append(f'const unsigned l3_asset_hero_part_count={len(parts)};')
 lines.append(f'const unsigned l3_asset_letter_mesh={mesh_ids[animation["collectible_mesh"]]};')
 for name in ['static_mesh','rotor_mesh']:lines.append(f'const unsigned l3_asset_windmill_{name}={mesh_ids[animation["windmill"][name]]};')
 lines.append('const L3Vec3 l3_asset_windmill_rotor_pivot='+vec(animation['windmill']['rotor_pivot'])+';')
 data='\n'.join(lines)+'\n';output.write_text(data)
 files=[HERE/'scene.json',HERE/'meshes.json',HERE/'heightfield.json',HERE/'generated.h',Path(__file__),*[texture_dir/t['file'] for t in textures]]
 report=dict(status='PASS',scope='Deterministic G3D1 asset packing and limits; compilation/runtime rendering are separate checks.',meshes=len(catalogue),groups=len(groups),instances=len(scene['instances']),
  maximum_group_vertices=max(g['nv'] for g in groups),maximum_group_faces=max(g['nf'] for g in groups),geometry_bytes=geometry_bytes,texture_bytes=len(textures)*32768,
  texture_directory=str(texture_dir),object_uv_projection=project_uv,
  inputs={str(p.relative_to(HERE.parent)):hashlib.sha256(p.read_bytes()).hexdigest() for p in files},data_c_sha256=hashlib.sha256(data.encode()).hexdigest())
 report_path=output.with_suffix('.validation.json') if args.output else HERE/'export_validation.json'
 report_path.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps({k:v for k,v in report.items() if k not in ['inputs','data_c_sha256']}))

if __name__=='__main__':main()
