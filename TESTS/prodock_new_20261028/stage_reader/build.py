#!/usr/bin/env python3
"""Pin the proven raw-LZ4 decoder and exact FM4A payload; no hardware."""
from pathlib import Path
import hashlib,json,shutil,subprocess,zlib
here=Path(__file__).resolve().parent
root=next(p for p in here.parents if (p/'ARCHI/COMPATIBILITE_CARTES.md').is_file())
elf=root/'games/luma3d/build/festival_memory_metrics_20261028_r4/luma3d-riscv'
packed=root/'games/luma3d/tests/hardware/festival_metrics_20261028_resume_prepared_r4/metrics-r4.full.lz4'
source=root/'games/luma3d/tests/runtime_helper.c'
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
assert sha(elf)=='6b8d3eeb273e03be38eb73a2ff6fee60dad16678316bfdacb52b4db308fec3f7'
assert len(elf.read_bytes())==16640496 and zlib.crc32(elf.read_bytes())==0xfa358bf4
text=source.read_text();decoder=text[text.index('static int unpack('):text.index('static uint32_t crc(')]
(here/'lz4_unpack.h').write_text('/* Exact decoder excerpt from games/luma3d/tests/runtime_helper.c; generated by build.py. */\n'+decoder)
shutil.copyfile(packed,here/'fm4a.full.lz4')
(here/'stage_identity.h').write_text(f'#define PACKED_BYTES {packed.stat().st_size}u\n#define PACKED_CRC 0x{zlib.crc32(packed.read_bytes()):08x}u\n#define ELF_BYTES 16640496u\n#define ELF_CRC 0xfa358bf4u\n')
cmd=[str(root/'linux/build/userbin/riscv32-prodock-linux-gcc'),'-std=c11','-Os','-Wall','-Wextra','-Werror','-Wno-misleading-indentation','-static','-ffunction-sections','-fdata-sections','-Wl,--gc-sections','-s',str(here/'stage_reader.c'),'-o',str(here/'stage_reader')]
subprocess.run(cmd,check=True)
files=[here/'stage_reader.c',here/'stage_reader',here/'stage_identity.h',here/'lz4_unpack.h',here/'fm4a.full.lz4',source,elf]
r={'hardware':False,'source_unchanged':True,'command':cmd,'physical_stage':'0x04000000','mmap_offset':'0x03800000','map_bytes':(packed.stat().st_size+4095)&~4095,'elf_crc32':'fa358bf4','packed_crc32':f'{zlib.crc32(packed.read_bytes()):08x}','files':{str(p.relative_to(root)):{'bytes':p.stat().st_size,'sha256':sha(p)} for p in files}}
(here/'manifest.json').write_text(json.dumps(r,indent=2)+'\n');print(json.dumps(r,indent=2))
