#!/usr/bin/env python3
"""Compile the real V1 scene/API, independently rasterize and optionally verify full RTL DDR contents."""
import argparse,json,struct,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'TESTS'))
from test_gpu_v1 import Model,SLOT
from PIL import Image
HARNESS=r'''
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "gpu_v1_scene.h"
#include "build/gpu_font.h"
static FILE *commands;
static void emit(const gpu_command *c){for(unsigned i=0;i<8;++i)fprintf(commands,"%08x\n",c->words[i]);}
int main(int argc,char **argv){
    if(argc!=5)return 2;
    unsigned scene=(unsigned)atoi(argv[1]),phase=(unsigned)atoi(argv[2]);
    commands=fopen(argv[3],"w");if(!commands)return 3;
    uint16_t *assets=malloc(1048576);if(!assets)return 4;
    for(unsigned i=0;i<1048576;++i)((unsigned char *)assets)[i]=(i*29+(i>>11))&255;
    v1_assets(assets,gpu_font);FILE *f=fopen(argv[4],"wb");if(!f)return 5;
    fwrite(assets,1,1048576,f);fclose(f);free(assets);
    gpu_v1_context c;gpu_v1_init(&c,emit);gpu_v1_invalidate(&c);
    int valid=v1_scene(&c,scene,phase,0);fclose(commands);return valid?0:6;
}
'''
def fnv(data):
    h=2166136261
    for b in data:h=((h^b)*16777619)&0xffffffff
    return h

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,required=True);p.add_argument('--rtl',action='store_true');p.add_argument('--write-header',action='store_true');a=p.parse_args();out=a.out.resolve();out.mkdir(parents=True,exist_ok=True)
    (out/'harness.c').write_text(HARNESS)
    subprocess.run(['cc','-O2','-Wall','-Wextra','-Werror','-fsanitize=undefined','-fno-sanitize-recover=all','-I'+str(ROOT/'fw_console'),str(out/'harness.c'),str(ROOT/'fw_console/gpu_v1.c'),'-o',str(out/'scene')],check=True)
    executable=None
    if a.rtl:
        sources=['TESTS/rtl/gpu_accel_tb.sv']+['tang/rtl/video/'+s+'.v' for s in ['gpu_accel','gpu_geometry','gpu_geom_div','blitter','gpu_raster','gpu_v1','gpu_texture_cache','gpu_copy565','gpu_perspective','gpu_triangle','gpu_blit_dma','font_ram']]+['tang/rtl/board/'+s+'.v' for s in ['ddr_dcfifo','cdc_word','ddr_gpu_arb']]
        with (out/'build.log').open('w') as log:subprocess.run(['verilator','--binary','-j','4','--timing','-Wno-fatal','--top-module','gpu_accel_tb','-GDEPTH_SLOT=2','--Mdir',str(out/'obj')]+[str(ROOT/s) for s in sources],stdout=log,stderr=log,check=True)
        executable=out/'obj/Vgpu_accel_tb'
    font=[int(s,16) for s in (ROOT/'tang/rtl/video/font8x16.hex').read_text().split()]
    title=b'GPU V1  400x240 + HUD 800x480';results=[]
    for scene in range(3):
        for phase in (0,17,37,63):
            stage=out/f'scene{scene}_phase{phase}';stage.mkdir(exist_ok=True)
            subprocess.run([str(out/'scene'),str(scene),str(phase),str(stage/'commands.hex'),str(stage/'assets.bin')],check=True)
            words=[int(v,16) for v in (stage/'commands.hex').read_text().split()]
            m=Model(depth_slot=2);m.memory[:2*SLOT]=bytes([0xa5])*(2*SLOT);m.memory[2*SLOT:]=(stage/'assets.bin').read_bytes();initial=bytes(m.memory)
            for i in range(0,len(words),8):m.apply(words[i:i+8])
            color=fnv(m.memory[:832*240+64]);depth=fnv(m.memory[SLOT:SLOT+832*240+64]);lcd=0;im=Image.new('RGB',(800,480));dst=im.load()
            for y in range(480):
                for x in range(800):
                    v=m.get(0x800000+(y//2)*832+(x//2)*2);r,g,b=((v>>11)*2+(v>>15),(v>>5)&63,(v&31)*2+((v>>4)&1))
                    index=0
                    if y<20:
                        if y<2 or y>=18:index=1
                        else:index=255 if x//8<len(title) and font[title[x//8]*16+y-2]&(128>>(x%8)) else 2
                    if index:r,g,b=(63,63,63) if index==255 else (0,40,63) if index==1 else (2,4,8)
                    lcd=(lcd+(r<<12)+(g<<6)+b)&0xffffffff;dst[x,y]=(r*255//63,g*255//63,b*255//63)
            im.save(stage/'expected.png')
            record=dict(scene=scene,phase=phase,color=color,depth=depth,lcd=lcd,commands=len(words)//8,fragments=m.passed)
            if executable:
                for name,data in [('expected.hex',m.memory),('initial.hex',initial)]:
                    (stage/name).write_text(''.join(f'{v:02x}\n' for v in data))
                (stage/'font8x16.hex').write_text((ROOT/'tang/rtl/video/font8x16.hex').read_text())
                with (stage/'rtl.log').open('w') as log:subprocess.run([str(executable),f'+ncmd={len(words)//8}','+v1_bad=0',f'+v1_pass={m.passed}','+rgbinit=3'],cwd=stage,stdout=log,stderr=log,check=True)
                record['rtl_exact']=True
            results.append(record);print(json.dumps(record),flush=True)
    (out/'result.json').write_text(json.dumps(results,indent=2)+'\n')
    if a.write_header:
        (ROOT/'fw_console/gpu_v1_expected.h').write_text('// Generated by tools/render_gpu_v1.py; independent integer pixel reference.\nstatic const unsigned v1_phases[4]={0,17,37,63};\nstatic const uint32_t v1_expected[3][4][3]={\n'+',\n'.join(' {'+','.join('{0x%08xU,0x%08xU,0x%08xU}'%(r['color'],r['depth'],r['lcd']) for r in results if r['scene']==s)+'}' for s in range(3))+'\n};\n')
if __name__=='__main__':main()
